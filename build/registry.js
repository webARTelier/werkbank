"use strict"

const fs = require("fs")
const fsp = fs.promises
const path = require("path")

const config = require("./config")

// Regenerate dist/js/registry.js from the compiled modules in dist/js/modules.
// Component modules go into `registry` (lazy, per-element); modules listed in
// config.registry.globalModules go into `globalRegistry` (init once per page).
async function generateRegistry() {
  const { modulesDir, globalModules, moduleSuffix, outFile } = config.registry

  let files = []
  try {
    files = await fsp.readdir(modulesDir)
  } catch {
    files = []
  }

  const names = files
    .filter((f) => f.endsWith(moduleSuffix))
    .map((f) => f.slice(0, -moduleSuffix.length))
    .sort((a, b) => a.localeCompare(b))

  const globalSet = new Set(globalModules)
  const line = (name) =>
    `  ${name}: () => import('./modules/${name}${moduleSuffix}'),`

  const regEntries = names.filter((n) => !globalSet.has(n))
  const globalEntries = names.filter((n) => globalSet.has(n))

  const stripTrailingComma = (arr) =>
    arr.map((n, i) => (i === arr.length - 1 ? line(n).replace(/,$/, "") : line(n)))

  const out =
    "// this file is auto-generated by gulp\n" +
    "export const registry = {\n" +
    stripTrailingComma(regEntries).join("\n") +
    "\n}\n\n" +
    "export const globalRegistry = {\n" +
    stripTrailingComma(globalEntries).join("\n") +
    "\n}\n"

  await fsp.mkdir(path.dirname(outFile), { recursive: true })
  await fsp.writeFile(outFile, out)

  return { registry: regEntries, globalRegistry: globalEntries }
}

module.exports = { generateRegistry }
